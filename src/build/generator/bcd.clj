(ns build.generator.bcd
  "Shadow-cljs build hook that reads the @mdn/browser-compat-data npm
   package and generates a reduced CLJS data namespace
   (generated.attribute-data) containing only the SVG compatibility
   data used by the app.

   The full dataset is ~19MB of JSON covering all browsers and web
   features; the generated file keeps only the `svg` subtree, and within
   it only the fields the attribute utils consume (`mdn_url`, `spec_url`,
   `status`, and per-browser added versions). BCD support entries are
   flattened to the `version_added` of the standard implementation (the
   first entry, per BCD's own ordering), dropping the prefixed and
   partial-implementation variants the UI cannot represent, so the rest
   is not bundled into the renderer."
  (:require
   [clojure.java.io :as io]
   [clojure.pprint :as pprint]
   [cognitect.transit :as transit]))

(defn bcd-file-path! []
  (io/file "node_modules" "@mdn" "browser-compat-data" "data.json"))

(defn output-file-path! []
  (io/file "src" "generated" "attribute_data.cljs"))

(defn- support-version
  [entry]
  (:version_added (if (sequential? entry) (first entry) entry)))

(defn- reduce-support
  [support]
  (into {}
        (map (fn [[browser entry]] [browser (support-version entry)]))
        support))

(defn- reduce-compat
  [c]
  (-> (select-keys c [:mdn_url :spec_url :status :support])
      (update :support reduce-support)))

(defn- reduce-node
  [node]
  (into {}
        (map (fn [[k v]]
               [k (if (= k :__compat) (reduce-compat v) (reduce-node v))]))
        node))

(defn- reduced-svg
  [data]
  (into {}
        (map (fn [[group nodes]]
               [group (into {} (map (fn [[k v]] [k (reduce-node v)])) nodes)]))
        (select-keys (:svg data) [:elements :global_attributes])))

(defn- keywordize
  [x]
  (cond
    (map? x) (into {} (map (fn [[k v]] [(keyword k) (keywordize v)]) x))
    (sequential? x) (into (empty x) (map keywordize) x)
    :else x))

(defn read-bcd!
  []
  (keywordize
   (with-open [in (io/input-stream (bcd-file-path!))]
     (transit/read (transit/reader in :json)))))

(defn generate-source
  [data]
  (str ";; ============================================================\n"
       ";; AUTO-GENERATED — DO NOT EDIT\n"
       ";; Generated by build.generator.bcd from @mdn/browser-compat-data\n"
       ";; ============================================================\n"
       "(ns generated.attribute-data)\n"
       "\n"
       "(def data\n"
       "  "
       (binding [pprint/*print-right-margin* 120]
         (with-out-str (pprint/pprint data)))
       ")\n"))

(defn generate!
  []
  (let [data (reduced-svg (read-bcd!))
        output (output-file-path!)
        new-source (generate-source data)
        changed? (or (not (.exists output))
                     (not= (slurp output) new-source))]
    (when changed?
      (io/make-parents output)
      (spit output new-source)
      (println (str "[bcd-reducer] Generated " (.getPath output)
                    " (" (count (:elements data)) " elements, "
                    (count (:global_attributes data))
                    " global attributes)")))
    changed?))

(defn ^:export hook!
  {:shadow.build/stages #{:configure :compile-prepare}}
  [build-state & _args]
  (case (:shadow.build/stage build-state)
    :configure (do (generate!)
                   build-state)
    :compile-prepare (do (generate!)
                         build-state)))
