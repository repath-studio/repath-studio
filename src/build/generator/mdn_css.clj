(ns build.generator.mdn-css
  "Reduces the mdn-data npm package down to what the attribute card renders
   and writes it out as a data namespace, so that the app can read that
   instead of the package.

   The app only ever reads `css/properties.json` and `l10n/css.json`, while
   the package index also pulls `api/inheritance` and the selectors,
   functions, at-rules, syntaxes, units and types tables into the renderer
   bundle. Of the property fields only the ones in `rendered-fields` reach the
   UI, and of the localizations only the values those fields hold, in the
   languages this app ships, are ever looked up.

   The keys stay strings because the compiler emits each keyword as a
   cljs.core.Keyword constructor call, and this data holds thousands of them.
   Every lookup here is by attribute name or by a value copied out of these
   same tables, so the consumer can keep using strings and keywordize only
   the single entry it hands to the UI."
  (:require
   [clojure.java.io :as io]
   [clojure.string :as string]
   [cognitect.transit :as transit]))

(def rendered-fields
  #{"appliesto" "computed" "percentages" "animatable" "animationType"
    "syntax" "initial" "mdn_url" "spec_url"})

(defn properties-input! []
  (io/file "node_modules" "mdn-data" "css" "properties.json"))

(defn l10n-input! []
  (io/file "node_modules" "mdn-data" "l10n" "css.json"))

(defn output-file []
  (io/file "src" "generated" "mdn_css.cljs"))

(defn app-languages []
  (into #{}
        (comp (filter #(.endsWith (.getName %) ".edn"))
              (map #(string/replace (.getName %) #"\\.edn$" "")))
        (file-seq (io/file "src" "lang"))))

(defn- read-json [file]
  (with-open [in (io/input-stream file)]
    (transit/read (transit/reader in :json))))

(defn- str-keys [x]
  (cond
    (map? x) (into {} (map (fn [[k v]] [(name k) (str-keys v)])) x)
    (sequential? x) (into [] (map str-keys) x)
    :else x))

(defn reduce-properties [properties]
  (into {}
        (map (fn [[k entry]] [k (select-keys entry rendered-fields)]))
        properties))

(defn translated-values [properties]
  (into #{}
        (comp (mapcat vals) (filter string?))
        (vals properties)))

(defn reachable-locales [languages]
  (into #{"en-US"} (mapcat #(vector % (subs % 0 2))) languages))

(defn reduce-l10n [l10n properties languages]
  (let [values (translated-values properties)
        locales (reachable-locales languages)]
    (into {}
          (keep (fn [[value translations]]
                  (when (contains? values value)
                    (let [kept (select-keys translations locales)]
                      (when (seq kept) [value kept])))))
          l10n)))

(defn- data-ns [properties l10n]
  (str
   ";; ============================================================\n"
   ";; AUTO-GENERATED — DO NOT EDIT\n"
   ";; Generated by build.generator.mdn-css from mdn-data\n"
   ";; ============================================================\n"
   "(ns generated.mdn-css\n"
   "  \"Reduced CSS property data and the localizations its fields reach.\n"
   "   Keys are strings because the compiler emits a cljs.core.Keyword\n"
   "   constructor call per keyword, and this data holds thousands.\")\n\n"
   "(def properties\n" (pr-str properties) ")\n\n"
   "(def l10n\n" (pr-str l10n) ")\n"))

(defn- write-if-changed! [file source]
  (when (or (not (.exists file)) (not= (slurp file) source))
    (io/make-parents file)
    (spit file source)
    (println (str "[mdn-css] Wrote " (.getPath file)
                  " (" (count source) " bytes)"))))

(defn generate! []
  (let [properties (str-keys (read-json (properties-input!)))
        l10n (str-keys (read-json (l10n-input!)))
        languages (app-languages)
        properties' (reduce-properties properties)
        l10n' (reduce-l10n l10n properties' languages)]
    (write-if-changed! (output-file) (data-ns properties' l10n'))
    (println (str "[mdn-css] " (count properties') " properties, "
                  (count l10n') " l10n entries for " (count languages)
                  " languages"))))
